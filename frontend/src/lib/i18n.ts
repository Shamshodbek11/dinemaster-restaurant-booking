/** Kalit shu tilda bevosita tarjima qilinganmi (testlar uchun: til aralashib qolmasin) */
export function hasTranslation(key: string, lang: Language): boolean {
  return Boolean(translations[lang]?.[key]);
}

/** Tarjima. Matndagi {brand} — dastur nomi (lib/brand.ts). Topilmasa: o'zbekcha, keyin kalitning o'zi. */
export function t(key: string, lang: Language): string {
  const text = translations[lang]?.[key] || translations['uz']?.[key] || key;
  return text.includes('{brand}') ? text.split('{brand}').join(BRAND) : text;
}

/** {n}, {b} kabi o'rinbosarlarni qiymatlar bilan almashtiradi */
export function tf(key: string, lang: Language, values: Record<string, string | number>): string {
  let text = t(key, lang);
  for (const [k, v] of Object.entries(values)) text = text.split(`{${k}}`).join(String(v));
  return text;
}
